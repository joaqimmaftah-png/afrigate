-- Fresh-project baseline. Application data is accessed through authorized Node APIs.
-- No legacy records, demo accounts, or business content are inserted.
create table public.profiles (
 id uuid primary key references auth.users(id) on delete restrict,
 email text not null, full_name text not null,
 phone text, company_name text, company_tin text, company_address text,
 business_type text, position text,
 role text not null default 'customer' check (role in ('customer','consultant','admin')),
 is_active boolean not null default true,
 created_at timestamptz not null default now()
);
create table public.services (
 id bigint generated by default as identity primary key,
 slug text not null unique, title text not null,
 short_description text not null default '', description text not null default '',
 highlights jsonb not null default '[]'::jsonb check (jsonb_typeof(highlights) = 'array'),
 icon text not null default 'Briefcase', sort_order integer not null default 0,
 is_active boolean not null default true
);
create table public.consultations (
 id bigint generated by default as identity primary key, reference text unique,
 customer_id uuid not null references public.profiles(id),
 consultant_id uuid references public.profiles(id),
 service_id bigint not null references public.services(id),
 subject text not null, description text not null,
 urgency text not null default 'Standard' check (urgency in ('Standard','Priority','Urgent')),
 preferred_contact text not null default 'Portal messages',
 status text not null default 'Submitted' check (status in ('Submitted','Under Review','Assigned to Consultant','Awaiting Customer Information','In Progress','Completed','Closed')),
 outcome text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), completed_at timestamptz
);
create table public.status_history (
 id bigint generated by default as identity primary key,
 consultation_id bigint not null references public.consultations(id),
 status text not null check (status in ('Submitted','Under Review','Assigned to Consultant','Awaiting Customer Information','In Progress','Completed','Closed')),
 note text, changed_by uuid references public.profiles(id), changed_by_name text,
 created_at timestamptz not null default now()
);
create table public.messages (
 id bigint generated by default as identity primary key,
 consultation_id bigint not null references public.consultations(id),
 sender_id uuid references public.profiles(id),
 sender_role text not null check (sender_role in ('customer','consultant','admin','system')),
 kind text not null default 'message', body text not null,
 read_by_customer boolean not null default false, read_by_staff boolean not null default false,
 created_at timestamptz not null default now()
);
create table public.documents (
 id bigint generated by default as identity primary key,
 consultation_id bigint not null references public.consultations(id),
 uploaded_by uuid not null references public.profiles(id), uploader_role text not null,
 file_name text not null, storage_path text not null unique, mime_type text not null,
 size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 10485760),
 category text not null default 'Other', is_report boolean not null default false, note text,
 created_at timestamptz not null default now()
);
create table public.appointments (
 id bigint generated by default as identity primary key,
 consultation_id bigint references public.consultations(id),
 customer_id uuid not null references public.profiles(id), consultant_id uuid references public.profiles(id),
 service_id bigint not null references public.services(id),
 scheduled_at timestamptz not null,
 duration_minutes integer not null default 60 check (duration_minutes in (30,45,60,90)),
 method text not null check (method in ('In-person meeting','Phone call','Video meeting','WhatsApp call')),
 status text not null default 'Requested' check (status in ('Requested','Confirmed','Completed','Cancelled')),
 notes text, meeting_link text, created_by uuid not null references public.profiles(id),
 created_at timestamptz not null default now()
);
create table public.notifications (
 id bigint generated by default as identity primary key, user_id uuid not null references public.profiles(id),
 title text not null, body text not null, link text, is_read boolean not null default false,
 created_at timestamptz not null default now()
);
create table public.audit_logs (
 id bigint generated by default as identity primary key, actor_id uuid references public.profiles(id),
 actor_email text not null, actor_role text not null, action text not null,
 entity text not null, entity_id text, details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create table public.articles (
 id bigint generated by default as identity primary key, slug text not null unique,
 title text not null, excerpt text not null, body text not null,
 category text not null check (category in ('tax','news')), tag text,
 published boolean not null default false, source_url text,
 published_at timestamptz not null default now(), created_at timestamptz not null default now()
);
create table public.testimonials (
 id bigint generated by default as identity primary key,
 name text not null, company text, quote text not null, approved boolean not null default false,
 created_at timestamptz not null default now()
);
create table public.enquiries (
 id bigint generated by default as identity primary key,
 name text not null, email text not null, phone text, company text,
 service_id bigint references public.services(id), message text not null,
 status text not null default 'New' check (status in ('New','Contacted','Resolved')),
 created_at timestamptz not null default now()
);
create index profiles_role_idx on public.profiles(role, is_active);
create index consultations_customer_idx on public.consultations(customer_id, updated_at desc);
create index consultations_consultant_idx on public.consultations(consultant_id, updated_at desc);
create index consultations_service_idx on public.consultations(service_id);
create index consultations_status_idx on public.consultations(status);
create index status_history_consultation_idx on public.status_history(consultation_id, created_at);
create index messages_consultation_idx on public.messages(consultation_id, created_at);
create index messages_sender_idx on public.messages(sender_id);
create index documents_consultation_idx on public.documents(consultation_id, created_at);
create index documents_uploader_idx on public.documents(uploaded_by);
create index appointments_customer_idx on public.appointments(customer_id, scheduled_at);
create index appointments_consultant_idx on public.appointments(consultant_id, scheduled_at);
create index appointments_consultation_idx on public.appointments(consultation_id);
create index appointments_service_idx on public.appointments(service_id);
create index notifications_user_idx on public.notifications(user_id, is_read, created_at desc);
create index audit_logs_created_idx on public.audit_logs(created_at desc);
create index articles_published_idx on public.articles(published, published_at desc);
create index enquiries_service_idx on public.enquiries(service_id);
